"use babel";
// @flow

import Rx from "rxjs";
import { addPlanConfigIfNotExist } from "../../../ExecutionControlEpic/PlanConfigurationFeature/Actions/AddPlanConfig";
import { removeGeneratedPlans } from "../../../ExecutionControlEpic/PlanConfigurationFeature/Actions/RemoveGeneratedPlans";
import type { GeneratedPlanObject } from "../../../ExecutionControlEpic/PlanConfigurationFeature/Types/types.js.flow";
import type { Package, PackagesRefreshedAction } from "../Types/types.js.flow";
import { generatePlanId } from "../../../ExecutionControlEpic/PlanConfigurationFeature/Model/id";

const generatePlansEpic = (action$: Observable) => {
  return action$
    .ofType("PACKAGES_REFRESHED")
    .map((action: PackagesRefreshedAction) => {
      return Rx.Observable.from(action.payload.packages)
        .map((packageInfo: Package) => {
          if (packageInfo.plugin.generatePlansForPackage == null) {
            return [];
          }
          const generatePlanActions = packageInfo.plugin
            .generatePlansForPackage(packageInfo.path)
            .map((planObject: GeneratedPlanObject) =>
              addPlanConfigIfNotExist({
                id: generatePlanId(),
                name: planObject.name,
                tool: packageInfo.plugin.tool,
                autoGenerated: true,
                config: planObject.value,
                stager: { type: "integrated" },
                packageInfo,
              })
            );
          return [removeGeneratedPlans(packageInfo.plugin.tool), ...generatePlanActions];
        })
        .mergeAll();
    })
    .mergeAll();
};

export default generatePlansEpic;
